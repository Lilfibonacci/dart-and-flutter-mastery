void main(List<String> args) {
  // رشته‌ها حساس به حروف بزرگ و کوچک هستند،
  // به این معنی که:
  // Hello
  // با:
  // hello
  // متفاوت است، که با:
  // HELLO
  // متفاوت است.
  // این می‌تواند مشکل‌ساز باشد
  // اگر شما از آدرس‌های ایمیل
  // به عنوان شناسه‌های یکتا در پایگاه داده خود استفاده کنید.
  // آدرس‌های ایمیل به طور ذاتی
  // حساس به حروف بزرگ و کوچک نیستند.
  // شما نمی‌خواهید که برای:
  // spongebob@example.com
  // و:
  // SpongeBob@example.com
  // حساب‌های کاربری مختلف ایجاد کنید.

  // تعریف متغیر متنی با حروف بزرگ و کوچک نامرتب:
  String userInput = "ToWhiD@GmaIl.com";

  // toLowerCase()
  // تبدیل تمام حروف متن به حروف کوچک انگلیسی:
  // نکته: رشته‌ها در زبان:
  // Dart
  // تغییرناپذیر:
  // immutable
  // هستند،
  // یعنی متغیر اصلی دست‌نخورده باقی می‌ماند
  // و یک متن جدید تولید می‌شود.
  // کاربرد: یکسان‌سازی ورودی‌های کاربر
  // مانند ایمیل قبل از ذخیره یا جستجو:
  print(userInput.toLowerCase());
  // خروجی:
  // towhid@gmail.com

  // toUpperCase()
  // تبدیل تمام حروف متن به حروف بزرگ انگلیسی:
  String userInput2 = "ToWhiD@GmaIl.com";
  print(userInput2.toUpperCase());
  // خروجی:
  // TOWHID@GMAIL.COM

  // اصلاح (Trimming):
  // یکی از موارد رایجی که می‌خواهید حذف کنید،
  // فاصله‌های اضافی در ابتدا یا انتهای یک رشته است.
  // فاصله‌ها می‌توانند مشکل‌ساز باشند
  // زیرا دو رشته ممکن است به نظر مشابه باشند
  // اما در واقع متفاوت باشند.
  // حذف این فاصله‌ها اصطلاحاً اصلاح یا:
  // trim
  // نامیده می‌شود.

  // تعریف متغیر متنی همراه با فاصله‌های اضافه در ابتدا و انتها:
  String userInput3 = "  221b Baker St.  ";

  // trim()
  // حذف فاصله‌های خالی از هر دو طرف یعنی ابتدا و انتهای متن:
  // فاصله‌های بین کلمات بدون تغییر باقی می‌مانند:
  print(userInput3.trim());
  // خروجی:
  // 221b Baker St.

  // trimRight()
  // حذف فاصله‌های خالی فقط از سمت راست یعنی انتهای متن:
  print(userInput3.trimRight());
  // خروجی:
  //   221b Baker St.

  // trimLeft()
  // حذف فاصله‌های خالی فقط از سمت چپ یعنی ابتدای متن:
  print(userInput3.trimLeft());
  // خروجی:
  // 221b Baker St.

  // پر کردن (Padding):
  // گاهی اوقات شما نیاز دارید فضای اضافی یا کاراکترهای دیگر را
  // به ابتدا یا انتهای یک رشته اضافه کنید.
  // به عنوان مثال، اگر در حال ساخت یک ساعت دیجیتال باشید:

  // قالب‌بندی زمان - روش اول (رویکرد نادرست):
  final time = Duration(hours: 1, minutes: 2, seconds: 3);
  final hours = time.inHours;
  final minutes = time.inMinutes % 60;
  final seconds = time.inSeconds % 60;
  final timeString = "$hours:$minutes:$seconds";
  print(timeString);
  // خروجی غیرمنتظره:
  // 1:2:3

  // قالب‌بندی زمان - روش دوم (رویکرد صحیح و حرفه‌ای):
  // ۱. استفاده از عملگر باقیمانده برای دریافت دقیقه و ثانیه بین صفر تا ۵۹.
  // ۲. استفاده از متد:
  // padLeft()
  // برای پر کردن متن از سمت چپ و دو رقمی نگه‌داشتن اعداد.
  //
  // عدد ۲ در:
  // padLeft(2, '0')
  // به این معنی است که شما می‌خواهید حداقل طول دو کاراکتر باشد.
  // '0'
  // کاراکتر پرکننده‌ای است که می‌خواهید استفاده کنید.
  // اگر آن را مشخص نکرده بودید،
  // پرکننده به صورت پیش‌فرض کاراکتر فاصله می‌بود:

  final time1 = Duration(hours: 1, minutes: 2, seconds: 3);
  final hours1 = time1.inHours;
  final minutes1 = '${time1.inMinutes % 60}'.padLeft(2, '0');
  final seconds1 = '${time1.inSeconds % 60}'.padLeft(2, '0');
  final timeString1 = "$hours1:$minutes1:$seconds1";
  print(timeString1);
  // خروجی صحیح ساعت دیجیتال:
  // 1:02:03

  // split()
  // تجزیه یک رشته به لیستی از بخش‌ها:
  // فرض کنید یک خط از یک فایل داریم
  // که اطلاعات با کاما از هم جدا شده‌اند:
  final csvFileLine = 'Martin,Emma,122,Paris,France';

  // رشته را از محل کاراکتر مشخص‌شده برش می‌دهد.
  // نتیجه یک لیست از رشته‌هاست.
  // در اینجا هر جا کاما باشد یک برش ایجاد می‌شود:
  final parts = csvFileLine.split(',');
  print(parts);
  // خروجی:
  // [Martin, Emma, 122, Paris, France]
  // توجه داشته باشید که اکنون همه آن‌ها رشته‌های جداگانه هستند.

  // join()
  // عملکرد برعکس تجزیه: اتصال اجزای یک لیست با جداکننده دلخواه.
  // اجزای لیست را به هم می‌چسباند و یک رشته واحد تولید می‌کند.
  // در اینجا بین هر دو عنصر لیست یک علامت جداکننده قرار می‌گیرد:
  final newCsvLine = parts.join(' | ');
  print(newCsvLine);
  // خروجی:
  // Martin | Emma | 122 | Paris | France

  // replaceAll()
  // جایگزینی تمام رخدادهای یک عبارت با عبارت دیگر در رشته:
  // این متد رشته را جستجو می‌کند
  // و هر جا عبارت مورد نظر را پیدا کند جایگزین می‌کند.
  // در اینجا تمام فاصله‌های خالی با کاراکتر زیرخط جایگزین می‌شوند:
  const pharse = 'Practice makes perfect';
  final withUnderScore = pharse.replaceAll(' ', '_');
  print(withUnderScore);
  // خروجی:
  // Practice_makes_perfect

  // نکته:
  // اگر فقط نیاز دارید اولین رخداد یک الگو را جایگزین کنید،
  // به جای:
  // replaceAll
  // از:
  // replaceFirst
  // استفاده کنید.
}
